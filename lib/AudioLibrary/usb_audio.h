#pragma once
#ifndef AUDIO_USB_H
#define AUDIO_USB_H

#include <Arduino.h>
#include <atomic>
#include <stdint.h>
#include "AudioStream.h"

// Maximum number of channels represented by the public API. The first ESP32-S3
// backend currently supports mono/stereo because Arduino USBAudioCard does.
#ifndef AUDIO_USB_MAX_CHANNELS
#define AUDIO_USB_MAX_CHANNELS 8
#endif

#if AUDIO_USB_MAX_CHANNELS < 2
#error "AUDIO_USB_MAX_CHANNELS must be at least 2"
#endif

class AudioInputUSB;
class AudioOutputUSB;

namespace audio_usb_detail {
uint8_t normalizeChannelCount(uint8_t channels);
bool attachInput(AudioInputUSB *input, uint8_t channels);
void detachInput(AudioInputUSB *input);
void setInputEnabled(AudioInputUSB *input, bool enabled);
bool attachOutput(AudioOutputUSB *output, uint8_t channels);
void detachOutput(AudioOutputUSB *output);
void setOutputEnabled(AudioOutputUSB *output, bool enabled); 
bool start(float sampleRate);
bool isStarted();
bool canChangeSampleRate();
bool inputStreaming();
bool outputStreaming();
size_t readInput(int16_t *interleaved, size_t frames);
void discardInput();
bool writeOutput(const int16_t *interleaved, size_t frames);
} // namespace audio_usb_detail

/**
 * USB audio source: receives playback audio sent by the USB host.
 *
 * The channel layout follows AudioInputI2S: channel 0 is left, channel 1
 * is right. The initial Arduino ESP32-S3 backend currently supports 1 or 2
 * channels. The class API allows a higher channel count for future backends.
 *
 * USB device descriptors are registered when the backend is first started.
 * Construct this object before AudioMemory() and before USB.begin().
 */
class AudioInputUSB : public AudioStream {
  public:
    explicit AudioInputUSB(uint8_t channels = 2);
    ~AudioInputUSB() override;

    bool begin();
    void end();

    bool isRunning() const;
    bool isStreaming() const;
    uint8_t channelCount() const { return channels_; }

    // Sets the AudioStream-wide sample rate before USB is configured.
    // The USB descriptor advertises one fixed rate for this initial backend.
    bool setSampleRate(float sampleRate);

  protected:
    void update() override;
    bool beginHardware() override;

  private:
    uint8_t channels_;
    bool registered_ = false;
    std::atomic<bool> enabled_{false};

    static uint8_t normalize(uint8_t channels) {
        return audio_usb_detail::normalizeChannelCount(channels);
    }

    AudioInputUSB(const AudioInputUSB &) = delete;
    AudioInputUSB &operator=(const AudioInputUSB &) = delete;
};

/**
 * USB audio sink: sends audio generated by the AudioStream graph to the host.
 *
 * Use it like AudioOutputI2S; channel 0 is left and channel 1 is right.
 * Only mono and stereo are supported by the initial ESP32-S3 transport.
 */
class AudioOutputUSB : public AudioStream {
  public:
    explicit AudioOutputUSB(uint8_t channels = 2);
    ~AudioOutputUSB() override;

    bool begin();
    void end();

    bool isRunning() const;
    bool isStreaming() const;
    uint8_t channelCount() const { return channels_; }

    // Sets the AudioStream-wide sample rate before USB is configured.
    bool setSampleRate(float sampleRate);

  protected:
    void update() override;
    bool beginHardware() override;

  private:
    uint8_t channels_;
    bool registered_ = false;
    std::atomic<bool> enabled_{false};
    audio_block_t *inputQueueArray[AUDIO_USB_MAX_CHANNELS] = {};

    AudioOutputUSB(const AudioOutputUSB &) = delete;
    AudioOutputUSB &operator=(const AudioOutputUSB &) = delete;
};

#endif // AUDIO_USB_H
